const {test, expect} = require('@playwright/test');
const {login, editor} = require('./helpers');
const panel = page => page.locator('#drupal-off-canvas');
async function openImage(page) {
  await login(page);
  await page.getByLabel('Text format', {exact:true}).selectOption('inside_embedded');
  await page.locator('.ck-button_inside-embedded-content__default').click();
  await panel(page).locator('[name="config[plugin_id]"]').selectOption('inside.media_image');
  await expect(panel(page).locator('[data-inside-plugin="inside.media_image"]')).toBeVisible();
}
test('media: upload image through nested library, embed, save and reopen', async ({page}) => {
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await openImage(page);
  await panel(page).getByLabel('Caption', {exact:true}).fill('Image selected in the off-canvas panel');
  await panel(page).getByRole('button',{name:'Add media',exact:true}).click();
  const library = page.locator('#drupal-modal');
  await expect(library).toBeVisible();
  await expect(panel(page)).toBeVisible();
  await library.locator('input[type=file]').setInputFiles('tests/fixtures/media-library.png');
  await library.getByLabel('Alternative text', {exact:false}).fill('Blue Media Library integration test image');
  const modal = page.locator('.ui-dialog').filter({has:library});
  await modal.getByRole('button',{name:'Save',exact:true}).click();
  await modal.getByRole('button',{name:'Insert selected',exact:true}).click();
  await expect(library).not.toBeVisible();
  await expect(panel(page).locator('.media-library-item')).toHaveCount(1);
  await expect(panel(page).getByLabel('Caption', {exact:true})).toHaveValue('Image selected in the off-canvas panel');
  await panel(page).getByRole('button',{name:'Embed',exact:true}).click();
  await expect(page.locator('.inside-embedded-content-preview img')).toBeVisible();
  await expect.poll(() => page.locator('.inside-embedded-content-preview img').evaluate(img => img.complete && img.naturalWidth > 0)).toBeTruthy();
  await expect(page.locator('.inside-embedded-content-preview')).toContainText('Image selected in the off-canvas panel');
  await expect(page.locator('figure.ck-widget')).toHaveCount(1);
  await page.getByLabel('Title',{exact:true}).fill('Media Library off-canvas image test');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect(page.locator('article .inside-media-image img')).toHaveAttribute('alt','Blue Media Library integration test image');
  await expect.poll(() => page.locator('article .inside-media-image img').evaluate(img => img.complete && img.naturalWidth > 0)).toBeTruthy();
  const nodeUrl=page.url();
  await page.goto(nodeUrl+'/edit');
  await expect.poll(() => page.locator('.inside-embedded-content-preview img').evaluate(img => img.complete && img.naturalWidth > 0)).toBeTruthy();
  await expect(page.locator('[data-inside-embedded-content-preview="ready"]')).toBeVisible();
  await page.locator('figure.ck-widget').click();
  const editButton = page.locator('.ck-button_inside-embedded-content__edit');
  await editButton.focus();
  await editButton.press('Enter');
  await expect(panel(page).locator('.media-library-item')).toHaveCount(1);
  await expect(panel(page).getByLabel('Caption',{exact:true})).toHaveValue('Image selected in the off-canvas panel');
  await panel(page).getByLabel('Caption',{exact:true}).fill('Updated image caption');
  await panel(page).getByRole('button',{name:'Embed',exact:true}).click();
  await expect(page.locator('.inside-embedded-content-preview')).toContainText('Updated image caption');
  await expect(page.locator('figure.ck-widget')).toHaveCount(1);
  expect(errors).toEqual([]);
});

test('media: existing selection, removal and nested cancel preserve the editor', async ({page}) => {
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await openImage(page);
  await panel(page).getByRole('button',{name:'Embed',exact:true}).click();
  await expect(panel(page)).toContainText('Select an image you have permission to view.');
  await panel(page).getByLabel('Caption',{exact:true}).fill('Existing library image');
  async function selectExisting() {
    await panel(page).getByRole('button',{name:'Add media',exact:true}).click();
    const library=page.locator('#drupal-modal');
    await library.locator('.js-media-library-item input[type=checkbox]').first().check();
    await page.locator('.ui-dialog').filter({has:library}).getByRole('button',{name:'Insert selected',exact:true}).click();
    await expect(library).not.toBeVisible();
    await expect(panel(page).locator('.media-library-item')).toHaveCount(1);
  }
  await panel(page).getByRole('button',{name:'Add media',exact:true}).click();
  await page.locator('.ui-dialog').filter({has:page.locator('#drupal-modal')}).getByRole('button',{name:'Close',exact:true}).click();
  await expect(panel(page)).toBeVisible();
  await expect(panel(page).getByLabel('Caption',{exact:true})).toHaveValue('Existing library image');
  await selectExisting();
  await panel(page).locator('.media-library-item__remove').click();
  await expect(panel(page).locator('.media-library-item')).toHaveCount(0);
  await selectExisting();
  await panel(page).getByRole('button',{name:'Embed',exact:true}).click();
  await expect(page.locator('.inside-embedded-content-preview img')).toBeVisible();
  await expect.poll(() => page.locator('.inside-embedded-content-preview img').evaluate(img => img.complete && img.naturalWidth > 0)).toBeTruthy();
  const before=await editor(page,ed=>ed.getData());
  await page.locator('figure.ck-widget').click();
  await page.locator('.ck-button_inside-embedded-content__edit').click();
  await panel(page).locator('.media-library-item__remove').click();
  await expect(panel(page).locator('.media-library-item')).toHaveCount(0);
  await page.locator('.ui-dialog-off-canvas .ui-dialog-titlebar-close').click();
  await expect(panel(page)).not.toBeVisible();
  expect(await editor(page,ed=>ed.getData())).toBe(before);
  await expect(page.locator('figure.ck-widget')).toHaveCount(1);
  expect(errors).toEqual([]);
});
